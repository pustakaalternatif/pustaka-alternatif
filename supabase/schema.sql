create or replace function public.is_active_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users u
    where u.user_id = auth.uid()
      and u.is_active = true
      and u.role in ('admin', 'editor')
  );
$$;

revoke all on function public.is_active_admin() from public;
grant execute on function public.is_active_admin() to anon, authenticated;

grant select on public.books, public.authors, public.categories, public.site_settings to anon, authenticated;
grant insert, update, delete on public.books, public.authors, public.categories, public.site_settings to authenticated;
grant select on public.admin_users to authenticated;
grant select, insert, update, delete on public.orders to authenticated;
grant insert on public.orders to anon;
grant usage, select on all sequences in schema public to authenticated;

