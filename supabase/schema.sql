-- Remove any earlier, broader order policies before granting the new least-privilege rules.
do $$
declare existing_policy record;
begin
  for existing_policy in
    select policyname from pg_policies
    where schemaname = 'public' and tablename = 'orders'
  loop
    execute format('drop policy if exists %I on public.orders', existing_policy.policyname);
  end loop;
end;
$$;

drop policy if exists orders_public_create_validated on public.orders;
create policy orders_public_create_validated on public.orders
  for insert to anon, authenticated
  with check (
    status = 'Baru'
    and quantity between 1 and 99
    and unit_price_idr > 0
    and total_price_idr = unit_price_idr * quantity
    and length(btrim(name)) between 2 and 120
    and length(btrim(phone)) between 7 and 24
    and length(btrim(address)) between 5 and 500
    and length(btrim(location)) between 2 and 2048
    and length(note) <= 1000
    and exists (
      select 1
      from public.books b
      where b.id = book_id
        and b.status = 'Telah terbit'
        and b.price_idr = unit_price_idr
        and b.slug = book_slug
        and b.title = book_title
        and b.author_name = book_author
    )
  );
drop policy if exists orders_admin_read on public.orders;
create policy orders_admin_read on public.orders
  for select to authenticated using (public.is_active_admin());
drop policy if exists orders_admin_update on public.orders;
create policy orders_admin_update on public.orders
  for update to authenticated
  using (public.is_active_admin())
  with check (public.is_active_admin());
drop policy if exists orders_admin_delete on public.orders;
create policy orders_admin_delete on public.orders
  for delete to authenticated using (public.is_active_admin());

