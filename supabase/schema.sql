create extension if not exists pgcrypto;

create table if not exists public.authors (
  id text primary key,
  name text not null unique,
  bio text not null default '',
  focus text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  name text primary key check (length(btrim(name)) > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  long_title text not null default '',
  author_id text references public.authors(id) on delete set null,
  author_name text not null,
  author_note text not null default '',
  year text not null default '',
  category text not null references public.categories(name) on update cascade on delete restrict,
  status text not null default 'Draf' check (status in ('Draf', 'Akan terbit', 'Telah terbit')),
  isbn text,
  price_idr bigint check (price_idr is null or price_idr > 0),
  stock integer check (stock is null or stock >= 0),
  image_url text not null,
  back_image_url text,
  color text not null default 'blue',
  description text not null default '',
  featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

